"""Destructive-isolated CI-only Postgres backup/restore acceptance.

Never runs against production: both DSNs must point to the exact local
ephemeral 'ridge_ci' database, CI=true, port 5432. All restore database names
are generated by this runner. Credentials never enter command-line argv.

Checks pg_dump + pg_restore at the storage layer, then exercises production
PostgresPrivateSessionStore and PostgresPrivateTurnQueue with the restored
least-privileged runtime user. This is NOT a PITR, failover or DR RTO guarantee.
"""
from __future__ import annotations

import os
from pathlib import Path
import subprocess
import tempfile
from urllib.parse import unquote, urlsplit, urlunsplit
from uuid import uuid4

from core.memory import MemoryScope
from core.persistence.postgres_sessions import PostgresPrivateSessionStore
from core.persistence.postgres_turn_queue import PostgresPrivateTurnQueue


def _safe_ci_dsn(name: str) -> tuple[str, str, int, str, str]:
    dsn = os.environ.get(name, "")
    parsed = urlsplit(dsn)
    if (
        os.environ.get("CI") != "true"
        or parsed.scheme not in {"postgres", "postgresql"}
        or parsed.hostname != "127.0.0.1"
        or (parsed.port or 5432) != 5432
        or parsed.path != "/ridge_ci"
        or not parsed.username or not parsed.password
        or parsed.query or parsed.fragment
    ):
        raise RuntimeError("Restore drill requires exact disposable loopback CI DSNs")
    return dsn, unquote(parsed.username), 5432, unquote(parsed.password), parsed.hostname


def _with_database(dsn: str, dbname: str) -> str:
    parsed = urlsplit(dsn)
    return urlunsplit(parsed._replace(path="/" + dbname))


def _pg_cli(binary: str, *, user: str, password: str, host: str,
            port: int, database: str, archive: Path) -> None:
    env = dict(os.environ)
    env["PGPASSWORD"] = password
    if binary == "pg_dump":
        args = [
            "pg_dump", "--format=custom", "--no-password",
            "--host", host, "--port", str(port), "--username", user,
            "--dbname", database, "--file", str(archive),
        ]
    elif binary == "pg_restore":
        args = [
            "pg_restore", "--exit-on-error", "--single-transaction",
            "--no-owner", "--no-password", "--host", host,
            "--port", str(port), "--username", user,
            "--dbname", database, str(archive),
        ]
    else:
        raise ValueError("Invalid restore drill command")
    # Do not leak environment or password-bearing errors into CI logs.
    result = subprocess.run(
        args, env=env, check=False, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE, timeout=120,
    )
    if result.returncode != 0:
        raise RuntimeError(f"{binary} failed; inspect isolated CI database logs")


def main() -> int:
    source, runtime_user, port, runtime_password, host = _safe_ci_dsn("RIDGE_TEST_POSTGRES_DSN")
    admin_dsn, admin_user, _, admin_password, _ = _safe_ci_dsn("RIDGE_TEST_POSTGRES_ADMIN_DSN")
    if admin_user == runtime_user:
        raise RuntimeError("Backup/restore must use separate admin and runtime roles")
    import psycopg
    from psycopg import sql

    target_name = "ridge_dr_" + uuid4().hex[:12]
    restored_dsn = _with_database(source, target_name)
    suffix = uuid4().hex[:8]
    a = MemoryScope("dr-a-" + suffix, "test-user", "private")
    b = MemoryScope("dr-b-" + suffix, "test-user", "private")
    c = MemoryScope("dr-c-" + suffix, "test-user", "private")
    sid = uuid4().hex[:12]
    original_sessions = PostgresPrivateSessionStore(source)
    original_turns = PostgresPrivateTurnQueue(source)
    created = False
    restored = False
    with tempfile.TemporaryDirectory(prefix="ridge-postgres-dr-") as temp:
        archive = Path(temp) / "database.backup"
        try:
            original_sessions.create(a, sid, title="Private A", snapshot={"principal": "owner-a"})
            original_sessions.create(b, sid, title="Private B", snapshot={"principal": "owner-b"})
            created = True
            turn_id = original_turns.enqueue(a, sid, idempotency_key="dr-job", payload={"kind": "test"})
            lease = original_turns.claim(a, worker_id="dr-worker", lease_seconds=20)
            assert lease is not None and lease.id == turn_id
            assert original_turns.complete(a, turn_id, worker_id="dr-worker",
                                           fence=lease.fence, result={"exit_code": 0})
            original_events = original_turns.events(a, sid)
            assert [e["state"] for e in original_events] == ["queued", "running", "completed"]
            assert original_turns.events(b, sid) == []

            _pg_cli("pg_dump", user=admin_user, password=admin_password, host=host,
                    port=port, database="ridge_ci", archive=archive)
            assert archive.is_file() and archive.stat().st_size > 0
            # Make source diverge AFTER backup: restore must not copy later work.
            original_turns.enqueue(a, sid, idempotency_key="after-backup", payload={"not": "in backup"})

            with psycopg.connect(admin_dsn, autocommit=True) as admin:
                with admin.cursor() as cur:
                    cur.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(target_name)))
            restored = True
            _pg_cli("pg_restore", user=admin_user, password=admin_password, host=host,
                    port=port, database=target_name, archive=archive)

            sessions = PostgresPrivateSessionStore(restored_dsn)
            turns = PostgresPrivateTurnQueue(restored_dsn)
            assert sessions.production_probe() is True
            assert turns.event_security_probe() is True
            assert sessions.get(a, sid).snapshot == {"principal": "owner-a"}
            assert sessions.get(b, sid).snapshot == {"principal": "owner-b"}
            assert sessions.get(c, sid) is None
            assert turns.events(a, sid) == original_events
            assert turns.events(b, sid) == []
            try:
                turns.events(c, sid)
            except LookupError:
                pass
            else:
                raise AssertionError("Out-of-scope session read was not denied")
            assert turns.enqueue(a, sid, idempotency_key="dr-job", payload={"kind": "test"}) == turn_id
            assert turns.events(a, sid) == original_events
            # The recovered store continues allocating owner-local cursors.
            turns.enqueue(a, sid, idempotency_key="new-work", payload={"kind": "test"})
            assert [e["id"] for e in turns.events(a, sid)] == [1, 2, 3, 4]
            print("RESTORE PASS: backup contents, immutable replay, tenant isolation, RLS and resumed cursor")
            return 0
        finally:
            if created:
                original_sessions.delete(a, sid)
                original_sessions.delete(b, sid)
            if restored:
                # These are fresh disposable dbs with no active connections.
                with psycopg.connect(admin_dsn, autocommit=True) as admin:
                    with admin.cursor() as cur:
                        cur.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(target_name)))


if __name__ == "__main__":
    raise SystemExit(main())
